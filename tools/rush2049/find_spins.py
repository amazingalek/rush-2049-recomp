"""Lists busy-wait loops in Rush 2049's code: short backward branches that re-read the same memory without
storing or calling anything.

ultramodern runs one game thread at a time and only delivers external messages inside OS calls, so such a loop
never ends unless it yields. Each hit in game code needs a yield hook in us.toml (libultra's own hardware polls are
in functions N64Recomp drops). Usage: find_spins.py [max_loop_instructions]
"""
import bisect
import os
import re
import struct
import sys

import rabbitizer

sys.path.insert(0, os.path.dirname(__file__))
from gen_syms import SECTIONS, RECOMP_ROM, OUT_PATH  # noqa: E402

max_len = int(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1].isdigit() else 6
rom = open(RECOMP_ROM, "rb").read()

funcs = sorted((int(v, 16), n) for n, v in re.findall(r'name = "(\w+)", vram = 0x([0-9A-F]+)', open(OUT_PATH).read()))
addrs = [a for a, _ in funcs]


def func_at(name, vram):
    i = bisect.bisect_right(addrs, vram) - 1
    return funcs[i][1] if i >= 0 else "?"


for name, rom_off, vram, size in SECTIONS:
    words = [struct.unpack_from(">I", rom, rom_off + i)[0] for i in range(0, size, 4)]
    for idx, w in enumerate(words):
        ins = rabbitizer.Instruction(w, vram + idx * 4)
        if not ins.isBranch() or ins.isJump():
            continue
        start = (ins.getBranchVramGeneric() - vram) // 4
        if not (0 <= start <= idx and idx - start < max_len):
            continue
        body = [rabbitizer.Instruction(words[j], vram + j * 4) for j in range(start, idx + 2)]
        if any(b.isJump() or b.isFunctionCall() or b.doesStore() for b in body):
            continue
        loads = [b for b in body if b.doesLoad()]
        if not loads:
            continue
        written = {b.getDestinationGpr() for b in body if b.modifiesRd() or b.modifiesRt()}
        written.discard(None)
        if any(l.rs in written for l in loads):
            continue
        print(f"{name} {func_at(name, vram + idx * 4)} {body[0].vram:08X}..{ins.vram:08X}")
        for b in body:
            print(f"    {b.vram:08X} {b.disassemble()}")


def emit_hooks():
    """With --toml: prints a [[patches.hook]] per single-instruction self-loop in game code, yielding only while
    the loop's own condition holds (the hook runs at the loop label, before the branch is evaluated)."""
    def r(reg):
        return reg.value

    conds = {
        "bnel": lambda i: f"ctx->r{r(i.rs)} != 0" if r(i.rt) == 0 else f"ctx->r{r(i.rs)} != ctx->r{r(i.rt)}",
        "bne": lambda i: f"ctx->r{r(i.rs)} != 0" if r(i.rt) == 0 else f"ctx->r{r(i.rs)} != ctx->r{r(i.rt)}",
        "beql": lambda i: f"ctx->r{r(i.rs)} == ctx->r{r(i.rt)}",
        "beq": lambda i: f"ctx->r{r(i.rs)} == ctx->r{r(i.rt)}",
        "bgtzl": lambda i: f"(int32_t)ctx->r{r(i.rs)} > 0",
        "bltzl": lambda i: f"(int32_t)ctx->r{r(i.rs)} < 0",
        "bgezl": lambda i: f"(int32_t)ctx->r{r(i.rs)} >= 0",
        "blezl": lambda i: f"(int32_t)ctx->r{r(i.rs)} <= 0",
    }
    for name, rom_off, vram, size in SECTIONS:
        for off in range(0, size, 4):
            ins = rabbitizer.Instruction(struct.unpack_from(">I", rom, rom_off + off)[0], vram + off)
            if not ins.isBranch() or ins.getBranchVramGeneric() != ins.vram:
                continue
            func = func_at(name, ins.vram)
            if not (func.startswith("func_") or func.startswith("ovl")):
                continue  # libultra: dropped or reimplemented by N64Recomp
            mnemonic = ins.getOpcodeName()
            if mnemonic == "b":
                continue  # `b .`: N64Recomp already turns it into pause_self
            # Only polls: the delay slot reloads a compared register from memory. Anything else (a counting delay
            # loop, say) must not yield on every iteration.
            delay = rabbitizer.Instruction(struct.unpack_from(">I", rom, rom_off + off + 4)[0], vram + off + 4)
            compared = {ins.rs} | ({ins.rt} if ins.hasOperandAlias(rabbitizer.OperandType.cpu_rt) else set())
            if not delay.doesLoad() or delay.rt not in compared:
                print(f"# skipped {func} 0x{ins.vram:08X}: {ins.disassemble()} / {delay.disassemble()}")
                continue
            print("[[patches.hook]]")
            print(f'func = "{func}"')
            print(f"before_vram = 0x{ins.vram:08X}")
            print(f'text = "    if ({conds[mnemonic](ins)}) yield_self_1ms(rdram);"')
            print()


if "--toml" in sys.argv:
    print("\n# ---- generated by find_spins.py --toml ----")
    emit_hooks()
